'use strict';
const a=require('node:assert/strict');const RT=require('../compat-runtime.js');
const row=(name,extra={})=>({uid:name,key:'signal',content:name,position:0,...extra});
const hist=[{role:'user',content:'signal'}],settings={localAdvancedRules:true,seed:'turn-001',recursiveScan:false};
const entries=[row('a',{extensions:{useProbability:true,probability:53}}),row('b',{extensions:{useProbability:true,probability:53}}),row('c',{extensions:{useProbability:true,probability:0}}),row('d',{extensions:{useProbability:true,probability:100}})];
const same=()=>RT.worldInfo(entries,hist,settings);
a.deepEqual(same().inserted,same().inserted,'Same turn, same roll');
a(!same().inserted.some(x=>x.entryId==='c'));
a(same().inserted.some(x=>x.entryId==='d'));
a.deepEqual(same().selectionAlgorithm,'deterministic_local_v1');
a(same().semanticGaps.some(g=>g.reason==='LOCAL_ADVANCED_RULES_NOT_ST_GOLDEN_EQUIVALENT'));
const group=[row('low',{extensions:{group:'scene',group_weight:10}}),row('high',{extensions:{group:'scene',group_weight:70}}),row('other',{extensions:{group:'tone',group_weight:15}})];
const result=RT.worldInfo(group,hist,settings);
a.equal(result.inserted.filter(e=>e.entryId==='low'||e.entryId==='high').length,1);
a(result.inserted.some(e=>e.entryId==='other'));
a.deepEqual(result.inserted,RT.worldInfo(group,hist,settings).inserted);
const excluded=RT.worldInfo(group,hist,{...settings,localAdvancedRules:false});
a.equal(excluded.inserted.length,0);
a(excluded.semanticGaps.length>0);
const expired=RT.worldInfo([row('s',{extensions:{sticky:2}})],hist,settings);
a.equal(expired.inserted.length,0,'Unsupported sticky cannot silently execute');
const card={kind:'character',raw:{name:'Hero'}};
const book={kind:'world_info',raw:{entries:[row('always',{extensions:{useProbability:true,probability:100}})]}};
const envelope=RT.createEnvelope({id:'story_1',turnIndex:4,worldInfoLocalAdvancedRules:true},[card,book],[],'signal');
a.equal(envelope.worldInfo.selectionAlgorithm,'deterministic_local_v1');
a(envelope.gaps.some(g=>g.reason==='LOCAL_ADVANCED_RULES_NOT_ST_GOLDEN_EQUIVALENT'));
const chanceBook={kind:'world_info',raw:{entries:[row('maybe',{extensions:{useProbability:true,probability:50}})]}};
const pre=RT.createEnvelope({id:'same',turnIndex:11,worldInfoLocalAdvancedRules:true},[card,chanceBook],[],'signal');
const dispatched=RT.createEnvelope({id:'same',turnIndex:12,pendingTurnId:'t123',worldInfoLocalAdvancedRules:true},[card,chanceBook],[],'signal');
a.deepEqual(pre.worldInfo.inserted,dispatched.worldInfo.inserted,'read-only preflight and committed turn use same seed');
console.log('PASS R11.12 local deterministic World Info group/probability, opt-in, trace and unsupported sticky');
